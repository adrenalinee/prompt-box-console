import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ColorSchemeScript, createTheme, mantineHtmlProps, MantineProvider } from "@mantine/core";
import React from "react";
import { Notifications } from "@mantine/notifications";
import { MyQueryClientProvider } from "@/components/layout/my-query-client-provider";
import { themeOverride } from "@/app/theme";
import { ModalsProvider } from "@mantine/modals";
import DefaultAlertModal from "@/components/layout/default-alert-modal";

const geistSans = Geist({
    variable: "--font-geist-sans",
    subsets: ["latin"],
});

const geistMono = Geist_Mono({
    variable: "--font-geist-mono",
    subsets: ["latin"],
});

export const metadata: Metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

const theme = createTheme(themeOverride)

export default function RootLayout({
   children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    return (
        <html lang="ko" {...mantineHtmlProps}>
        <head>
            <title></title>
            <ColorSchemeScript />
        </head>
        <body
            className={`${geistSans.variable} ${geistMono.variable} antialiased`}
        >
        <MantineProvider theme={theme}>
            <Notifications />
            <MyQueryClientProvider>
                <ModalsProvider
                    modals={{
                        alert: DefaultAlertModal,
                    }}
                >
                    {children}
                </ModalsProvider>
            </MyQueryClientProvider>
        </MantineProvider>
        </body>
        </html>
    );
}
